#!/usr/bin/env node
/**
 * Regenerates `projects/showcase/src/app/examples/source-code.ts` by reading
 * the actual model/service/component/template files straight off disk, so
 * the "Code" view in the showcase's Component examples tab always shows the
 * real, current source — never a hand-copied, driftable duplicate.
 *
 * Run after editing any of the referenced example files:
 *   node scripts/generate-example-sources.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..', 'projects', 'showcase', 'src', 'app');

const RESOURCES = [
  {
    kind: 'posts',
    label: 'Post',
    model: 'models/post.model.ts',
    service: 'resources/post-resource.ts',
    component: 'examples/post-manager.component.ts',
    template: 'examples/post-manager.component.html',
  },
  {
    kind: 'users',
    label: 'User',
    model: 'models/user.model.ts',
    service: 'resources/user-resource.ts',
    component: 'examples/user-manager.component.ts',
    template: 'examples/user-manager.component.html',
  },
  {
    kind: 'products',
    label: 'Product',
    model: 'models/product.model.ts',
    service: 'resources/product-resource.ts',
    component: 'examples/product-manager.component.ts',
    template: 'examples/product-manager.component.html',
  },
];

function read(relativePath) {
  return readFileSync(join(root, relativePath), 'utf8').replace(/\r\n/g, '\n').trimEnd();
}

function toTemplateLiteral(source) {
  return '`' + source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

const entries = RESOURCES.map((r) => {
  return `  ${r.kind}: {
    label: ${JSON.stringify(r.label)},
    files: [
      { name: ${JSON.stringify(r.model.split('/').pop())}, path: ${JSON.stringify(r.model)}, code: ${toTemplateLiteral(read(r.model))} },
      { name: ${JSON.stringify(r.service.split('/').pop())}, path: ${JSON.stringify(r.service)}, code: ${toTemplateLiteral(read(r.service))} },
      { name: ${JSON.stringify(r.component.split('/').pop())}, path: ${JSON.stringify(r.component)}, code: ${toTemplateLiteral(read(r.component))} },
      { name: ${JSON.stringify(r.template.split('/').pop())}, path: ${JSON.stringify(r.template)}, code: ${toTemplateLiteral(read(r.template))} },
    ],
  },`;
}).join('\n');

const output = `// AUTO-GENERATED by scripts/generate-example-sources.mjs — do not edit by hand.
// Regenerate with: node scripts/generate-example-sources.mjs
import type { ResourceKind } from '../models/domain';

export interface ExampleSourceFile {
  readonly name: string;
  readonly path: string;
  readonly code: string;
}

export interface ExampleSourceSet {
  readonly label: string;
  readonly files: readonly ExampleSourceFile[];
}

export const EXAMPLE_SOURCES: Record<ResourceKind, ExampleSourceSet> = {
${entries}
};
`;

const outPath = join(root, 'examples', 'source-code.ts');
writeFileSync(outPath, output, 'utf8');
console.log(`Wrote ${outPath}`);
